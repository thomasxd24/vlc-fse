  let lang = 'en';

  function plural(entry, n) {
    if (typeof entry !== 'object') return entry;
    const one = lang === 'fr' ? Math.abs(n) < 2 : Math.abs(n) === 1;
    return one ? entry.one : entry.other;
  }

  function t(key, vars) {
    let entry = dicts[lang][key];
    if (entry === undefined) entry = en[key];
    if (entry === undefined) return key;
    let s = plural(entry, vars && typeof vars.n === 'number' ? vars.n : 0);
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => {
        const v = vars[k];
        if (v === undefined) return m;
        return typeof v === 'number' && k !== 'code' ? v.toLocaleString(lang) : String(v);
      });
    }
    return s;
  }

